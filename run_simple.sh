#!/bin/bash
# Скрипт для запуска упрощенной версии шлюза для шаттлов (только CRLF)

# Переходим в директорию проекта
cd "$(dirname "$0")"

# Проверяем наличие виртуального окружения
if [ -d "venv" ]; then
    echo "Активация виртуального окружения..."
    source venv/bin/activate
fi

# Запускаем шлюз
echo "Запуск упрощенного шлюза для шаттлов (только CRLF)..."
python main_simple.py

# Если шлюз завершился с ошибкой, выводим сообщение
if [ $? -ne 0 ]; then
    echo "Шлюз завершился с ошибкой!"
    exit 1
fi

# Деактивируем виртуальное окружение
if [ -d "venv" ]; then
    deactivate
fi

echo "Шлюз остановлен"
exit 0