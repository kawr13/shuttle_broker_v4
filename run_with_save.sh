#!/bin/bash
# Скрипт для запуска шлюза с обновленным слушателем, сохраняющим шаттлы в файл конфигурации

# Переходим в директорию проекта
cd "$(dirname "$0")"

# Проверяем наличие виртуального окружения
if [ -d "venv" ]; then
    echo "Активация виртуального окружения..."
    source venv/bin/activate
fi

# Применяем обновленный слушатель
echo "Применение обновленного слушателя шаттлов..."
python apply_listener_update.py

# Если применение не удалось, спрашиваем пользователя
if [ $? -ne 0 ]; then
    echo "Не удалось применить обновленный слушатель. Продолжить запуск? (y/n)"
    read -r answer
    if [ "$answer" != "y" ]; then
        echo "Запуск отменен"
        exit 1
    fi
fi

# Выводим информацию о запуске
echo "Запуск шлюза WMS-Шаттл с обновленным слушателем..."
echo "- Терминатор команд: CRLF (\\r\\n)"
echo "- WMS API URL: $(grep -o 'api_url: "[^"]*"' config.yaml | cut -d'"' -f2)"
echo "- Автоматическое добавление неизвестных шаттлов: включено (с сохранением в файл)"

# Запускаем шлюз
python main.py

# Если шлюз завершился с ошибкой, выводим сообщение
if [ $? -ne 0 ]; then
    echo "Шлюз завершился с ошибкой!"
    exit 1
fi

# Деактивируем виртуальное окружение
if [ -d "venv" ]; then
    deactivate
fi

echo "Шлюз остановлен"
exit 0