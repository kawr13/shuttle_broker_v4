"""
Словарь с расшифровкой кодов ошибок шаттлов
"""

ERROR_CODES = {
    "1": "Аккумулятор разряжен",
    "2": "Превышения времени подъема/опускания платформы",
    "3": "Отсутствие движения ВПЕРЁД: нет вращения паразитного колеса (упёрся) при движении вперёд",
    "4": "Отсутствие движения: нет вращения паразитного колеса, или застрял при движении",
    "5": "Ошибка серводвигателя перемещения",
    "6": "Ошибка серводвигателя подъема/опускания платформы",
    "8": "Шаттл не в канале, режим HOME невозможен",
    "9": "Шаттл не готов к выполнению автоматических функций"
}

def get_error_description(error_code: str) -> str:
    """
    Получить описание ошибки по коду
    
    Args:
        error_code: Код ошибки (например, "1", "2", и т.д.)
        
    Returns:
        str: Описание ошибки или "Неизвестная ошибка" если код не найден
    """
    # Извлекаем числовой код из строки вида "F_CODE=1"
    if error_code.startswith("F_CODE="):
        code = error_code.split("=")[1].strip()
        # Если после F_CODE= идет число и текст, берем только число
        if code and code[0].isdigit():
            code = code[0]
    else:
        code = error_code
    
    return ERROR_CODES.get(code, "Неизвестная ошибка")