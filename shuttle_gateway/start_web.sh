#!/bin/bash
# Скрипт запуска шлюза шаттлов с веб-интерфейсом

echo "🚀 Запуск шлюза управления шаттлами с веб-интерфейсом..."
echo "🔗 Версия 3.5 с поддержкой постоянных TCP-соединений"

# Проверка зависимостей
if ! python3 -c "import aiohttp" 2>/dev/null; then
    echo "📦 Установка зависимостей..."
    pip3 install -r requirements.txt
fi

# Проверка наличия файлов для работы с постоянными соединениями
if [ ! -f "shuttle/connection_manager.py" ]; then
    echo "⚠️ Файл connection_manager.py не найден. Проверьте установку."
    exit 1
fi

# Настройка переменных окружения
export WEB_SERVER_URL="http://localhost:8080"

# Запрос токена для телеграм-бота (опционально)
read -p "Введите токен для телеграм-бота (оставьте пустым, чтобы пропустить): " TELEGRAM_TOKEN
if [ ! -z "$TELEGRAM_TOKEN" ]; then
    export TELEGRAM_TOKEN="$TELEGRAM_TOKEN"
    echo "🤖 Телеграм-бот будет запущен с указанным токеном"
else
    echo "🤖 Телеграм-бот не будет запущен"
fi

# Функция для обработки завершения работы
cleanup() {
    echo "
🛑 Получен сигнал завершения. Закрытие соединений..."
    # Здесь можно добавить дополнительные действия при завершении
    exit 0
}

# Регистрируем обработчик сигналов
trap cleanup SIGINT SIGTERM

# Запуск основного приложения
echo "🔄 Запуск основного процесса..."
python3 main.py

# Если процесс завершился, выводим сообщение
echo "⚠️ Процесс завершен. Нажмите Enter для выхода."
read