#!/bin/bash
# Скрипт для запуска шлюза с проверкой шаттлов

# Переходим в директорию проекта
cd "$(dirname "$0")"

# Проверяем наличие виртуального окружения
if [ -d "venv" ]; then
    echo "Активация виртуального окружения..."
    source venv/bin/activate
fi

# Проверяем шаттлы в конфигурации перед запуском
echo "Проверка шаттлов в конфигурации..."
python check_shuttles.py

# Запускаем шлюз
echo "Запуск шлюза..."
python main.py &
GATEWAY_PID=$!

# Ждем 30 секунд для работы шлюза
echo "Шлюз запущен, ожидание 30 секунд..."
sleep 30

# Останавливаем шлюз
echo "Остановка шлюза..."
kill $GATEWAY_PID
wait $GATEWAY_PID

# Проверяем шаттлы в конфигурации после остановки
echo "Проверка шаттлов в конфигурации после остановки..."
python check_shuttles.py

# Деактивируем виртуальное окружение
if [ -d "venv" ]; then
    deactivate
fi

echo "Готово!"
exit 0