#!/bin/bash
# Скрипт для запуска шлюза с проверкой конфигурации

# Переходим в директорию проекта
cd "$(dirname "$0")"

# Проверяем наличие виртуального окружения
if [ -d "venv" ]; then
    echo "Активация виртуального окружения..."
    source venv/bin/activate
fi

# Проверяем конфигурацию
echo "Проверка конфигурации..."
python check_config.py

# Если проверка не прошла, спрашиваем пользователя
if [ $? -ne 0 ]; then
    echo "Проверка конфигурации не прошла. Продолжить запуск? (y/n)"
    read -r answer
    if [ "$answer" != "y" ]; then
        echo "Запуск отменен"
        exit 1
    fi
fi

# Выводим информацию о запуске
echo "Запуск шлюза WMS-Шаттл..."
echo "- Терминатор команд: CRLF (\\r\\n)"
echo "- WMS API URL: $(grep -o 'api_url: "[^"]*"' config.yaml | cut -d'"' -f2)"
echo "- Автоматическое добавление неизвестных шаттлов: включено"

# Запускаем шлюз
python main.py

# Если шлюз завершился с ошибкой, выводим сообщение
if [ $? -ne 0 ]; then
    echo "Шлюз завершился с ошибкой!"
    exit 1
fi

# Деактивируем виртуальное окружение
if [ -d "venv" ]; then
    deactivate
fi

echo "Шлюз остановлен"
exit 0